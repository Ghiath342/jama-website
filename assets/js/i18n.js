(function () {
  const html = document.documentElement;
  const STORE_KEY = "jama-lang";
  let EN = null; // snapshot of English copy from markup

  function snapshot() {
    EN = {};
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      EN[el.getAttribute("data-i18n")] = el.innerHTML;
    });
    document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
      EN["ph:" + el.getAttribute("data-i18n-ph")] = el.getAttribute("placeholder") || "";
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      EN["aria:" + el.getAttribute("data-i18n-aria")] = el.getAttribute("aria-label") || "";
    });
  }

  function apply(lang) {
    const ar = lang === "ar";
    html.setAttribute("lang", ar ? "ar" : "en");
    html.setAttribute("dir", ar ? "rtl" : "ltr");

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const k = el.getAttribute("data-i18n");
      const v = ar ? AR[k] : EN[k];
      if (v != null) el.innerHTML = v;
    });
    document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
      const k = el.getAttribute("data-i18n-ph");
      const v = ar ? AR[k] : EN["ph:" + k];
      if (v != null) el.setAttribute("placeholder", v);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      const k = el.getAttribute("data-i18n-aria");
      const v = ar ? AR[k] : EN["aria:" + k];
      if (v != null) el.setAttribute("aria-label", v);
    });

    // meta
    const t = ar ? AR["meta.title"] : EN["meta.title"];
    const d = ar ? AR["meta.desc"] : EN["meta.desc"];
    if (t) document.title = t;
    const md = document.querySelector('meta[name="description"]');
    if (md && d) md.setAttribute("content", d);

    // toggle button states
    document.querySelectorAll("[data-lang]").forEach((b) => {
      b.classList.toggle("active", b.getAttribute("data-lang") === lang);
      b.setAttribute("aria-pressed", b.getAttribute("data-lang") === lang);
    });

    try { localStorage.setItem(STORE_KEY, lang); } catch (e) {}
    window.dispatchEvent(new CustomEvent("jama:lang", { detail: { lang } }));
  }

  function init() {
    snapshot();
    let lang = "ar"; // default Arabic per brief
    try { lang = localStorage.getItem(STORE_KEY) || "ar"; } catch (e) {}
    apply(lang);

    document.querySelectorAll("[data-lang]").forEach((b) => {
      b.addEventListener("click", () => apply(b.getAttribute("data-lang")));
    });
  }

  window.JAMA_I18N = { apply, AR };
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else { init(); }
})();
